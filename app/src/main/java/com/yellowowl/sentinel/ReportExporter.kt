package com.yellowowl.sentinel

import android.content.ActivityNotFoundException
import android.content.Context
import android.content.Intent
import androidx.core.content.FileProvider
import java.io.File
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

object ReportExporter {
    enum class Format(val ext: String, val mime: String, val label: String) {
        HTML("html", "text/html", "HTML report"),
        CSV("csv", "text/csv", "CSV"),
        JSON("json", "application/json", "JSON")
    }

    /** Builds the report in [format], writes it to app cache and opens the share sheet. */
    fun share(context: Context, findings: List<Finding>, format: Format): Boolean {
        val now = Date()
        val annotations = SentinelRepo.annotations.value
        val content = when (format) {
            Format.HTML -> ReportHtml.build(findings, now, BuildConfig.VERSION_NAME, annotations)
            Format.CSV -> ReportData.toCsv(findings, annotations)
            Format.JSON -> ReportData.toJson(findings, now, BuildConfig.VERSION_NAME, annotations)
        }

        val directory = File(context.cacheDir, "reports").apply { mkdirs() }
        directory.listFiles()?.forEach { it.delete() } // keep only the latest export on disk
        val stamp = SimpleDateFormat("yyyyMMdd-HHmm", Locale.US).format(now)
        val report = File(directory, "sentinel-report-$stamp.${format.ext}")
        report.writeText(content, Charsets.UTF_8)

        val uri = FileProvider.getUriForFile(context, "${context.packageName}.fileprovider", report)
        val send = Intent(Intent.ACTION_SEND).apply {
            type = format.mime
            putExtra(Intent.EXTRA_SUBJECT, "Sentinel Security report")
            putExtra(Intent.EXTRA_TEXT, "Security findings report generated by Sentinel (${findings.size} findings).")
            putExtra(Intent.EXTRA_STREAM, uri)
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
        return try {
            context.startActivity(
                Intent.createChooser(send, "Share ${format.label}").addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            )
            true
        } catch (_: ActivityNotFoundException) {
            false
        }
    }

    /** Back-compat shortcut used by the top-bar share button. */
    fun shareHtmlReport(context: Context, findings: List<Finding>): Boolean = share(context, findings, Format.HTML)
}
